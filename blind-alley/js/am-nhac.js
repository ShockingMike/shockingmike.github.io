
const TEN = { C: 0, D: 2, E: 4, F: 5, G: 7, A: 9, B: 11 };
export function nm(s) {
  const m = /^([A-G])(#|b)?(-?\d)$/.exec(s);
  if (!m) throw new Error('nốt sai: ' + s);
  return TEN[m[1]] + (m[2] === '#' ? 1 : m[2] === 'b' ? -1 : 0) + 12 * (+m[3] + 1);
}
const H = (ten, goc, tt, tay, dem, sau) => ({ ten, goc: nm(goc), tt: tt.map(nm), tay: tay.map(nm), dem: dem.map(nm), sau: sau ? { t: sau.t, ten: sau.ten, goc: nm(sau.goc || goc), tt: (sau.tt || tt).map(nm), tay: sau.tay.map(nm), dem: (sau.dem || dem).map(nm) } : null });
const G = (ds) => ds.map(([o, b, n, d]) => ({ o, b, m: nm(n), d }));

